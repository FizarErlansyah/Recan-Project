-- =============================================================================
-- 3. EXPIRY
-- A trigger instead of a rewrite of redeem_reward(), so every path that issues a
-- voucher gets an expiry and re-running 20261125 cannot drop it.
-- =============================================================================

create or replace function public.set_voucher_expiry()
returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.expires_at is null then
    select new.redeemed_at + make_interval(days => coalesce(i.validity_days, 30))
      into new.expires_at
    from public.catalog_items i
    where i.id = new.item_id;
  end if;
  return new;
end;
$$;

revoke all on function public.set_voucher_expiry() from public, anon, authenticated;

drop trigger if exists owned_vouchers_expiry on public.owned_vouchers;
create trigger owned_vouchers_expiry before insert on public.owned_vouchers
  for each row execute function public.set_voucher_expiry();


-- =============================================================================
-- 4. USE AT THE COUNTER
-- =============================================================================

drop function if exists public.use_voucher(text);
create function public.use_voucher(p_reference text)
returns table (
  reference text,
  status    text,
  used_at   timestamptz
)
language plpgsql security definer set search_path = ''
as $$
#variable_conflict use_column
declare
  v_uid     uuid := auth.uid();
  v_voucher public.owned_vouchers%rowtype;
begin
  if v_uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;

  select * into v_voucher
  from public.owned_vouchers o
  where o.reference = p_reference and o.user_id = v_uid
  for update;

  if not found then
    raise exception 'voucher_not_found' using errcode = 'P0002';
  end if;
  if v_voucher.status = 'used' then
    raise exception 'voucher_already_used' using errcode = 'P0001';
  end if;
  if v_voucher.status = 'expired' or v_voucher.expires_at <= now() then
    raise exception 'voucher_expired' using errcode = 'P0001';
  end if;

  return query
    update public.owned_vouchers o
       set status = 'used', used_at = now()
     where o.id = v_voucher.id
    returning o.reference, o.status, o.used_at;
end;
$$;

revoke all on function public.use_voucher(text) from public, anon;
grant execute on function public.use_voucher(text) to authenticated;


